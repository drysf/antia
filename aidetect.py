import argparse
import math
import os
import re
import subprocess
import sys
from pathlib import Path

SOURCE_EXTENSIONS = {
    ".c", ".h", ".cc", ".cpp", ".hh", ".hpp", ".cxx", ".py", ".java", ".js",
    ".ts", ".go", ".rs", ".sh", ".ml", ".mli", ".cs", ".rb", ".php", ".kt",
}
IGNORED_DIRS = {
    ".git", "node_modules", "build", "dist", "target", "venv", ".venv",
    "__pycache__", ".cache", ".idea", ".vscode",
}
AI_TOOL_FILES = [
    "CLAUDE.md", "AGENTS.md", "GEMINI.md", ".claude", ".cursor", ".cursorrules",
    ".windsurfrules", ".clinerules", ".aider.conf.yml", ".aider.chat.history.md",
    ".github/copilot-instructions.md", ".continue", ".codex",
]
AI_COMMIT_PATTERNS = re.compile(
    r"co-authored-by:.*(claude|copilot|cursor|gpt|openai|gemini|codex|aider)"
    r"|generated with \[?claude|claude code|chatgpt|copilot|cursor agent"
    r"|noreply@anthropic\.com",
    re.I,
)
AI_MENTIONS = re.compile(
    r"\b(chatgpt|gpt-[345]|claude|copilot|as an ai|language model"
    r"|generated by (an )?ai|ai[- ]generated)\b",
    re.I,
)
LLM_SYMBOLS = re.compile(
    "[—→←⇒✓✔✅❌⚠✨⭐\U0001f300-\U0001faff]"
)
LLM_PHRASES = re.compile(
    r"\b(helper function|utility function|edge cases?|this function|we need to"
    r"|make sure|ensure (that|the)|for simplicity|in a real|production"
    r"|robust|gracefully|handle the case|example usage|feel free|let's"
    r"|this ensures|to avoid|memory leaks?|properly|appropriate|simplified"
    r"|placeholder|your code here|implement(ed)? (this|here)|note:|important:"
    r"|optional:|step \d|fonction utilitaire|cas limites?|afin de|permet de"
    r"|on s'assure|gestion des erreurs|en production)\b",
    re.I,
)
STEP_VERBS = re.compile(
    r"^(check|initialize|initialise|allocate|free|create|return|handle"
    r"|update|calculate|compute|iterate|loop|skip|move|find|set|get|print"
    r"|read|write|parse|convert|add|remove|store|validate|ensure|use|build"
    r"|clean|copy|append|insert|reset|open|close|swap|count|split|save"
    r"|traverse|link|place|avoid|allow|make|send|wait|v[ée]rifie|initialis"
    r"|alloue|lib[èe]re|parcour|cr[ée]e|ajoute|retourne|calcule|copie"
    r"|met|g[èe]re|affiche|lit|[ée]crit)",
    re.I,
)
DOC_TAGS = re.compile(r"[@\\](brief|param|return|returns|note|details)\b")
DOCSTRING_SECTIONS = re.compile(r"^\s*(Args|Returns|Raises|Parameters|Example)s?:\s*$", re.M)
SECTION_BANNER = re.compile(r"^\s*(//|#|/\*)\s*[=\-*#]{5,}", re.M)
ERROR_PREFIX = re.compile(r"\"(Error|Warning|Usage): ")
CODE_FENCE = re.compile(r"^```", re.M)
BANNER_42 = re.compile(r"\A/\* \*{50,}.*?\*{50,} \*/\s*", re.S)


def color(text, code):
    if not sys.stdout.isatty():
        return text
    return f"\033[{code}m{text}\033[0m"


def collect_files(root):
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in IGNORED_DIRS]
        for name in filenames:
            path = Path(dirpath) / name
            if path.suffix not in SOURCE_EXTENSIONS:
                continue
            try:
                text = path.read_text(errors="ignore")
            except OSError:
                continue
            if len(text) > 200_000:
                continue
            if sum(1 for line in text.splitlines() if line.strip()) < 3:
                continue
            files.append((path, text))
    return sorted(files)


def extract_comments(text, suffix):
    if suffix in {".py", ".sh", ".rb"}:
        line_comments = re.findall(r"(?<![\"'$])#(?!!|include|define)\s?(.*)", text)
        block_comments = re.findall(r'"""(.*?)"""', text, re.S)
    else:
        line_comments = re.findall(r"(?<!:)//+\s?(.*)", text)
        block_comments = re.findall(r"/\*+(.*?)\*/", text, re.S)
    if suffix in {".ml", ".mli"}:
        block_comments = re.findall(r"\(\*(.*?)\*\)", text, re.S)
    comments = [c.strip() for c in line_comments]
    for block in block_comments:
        lines = [re.sub(r"^\s*\*?\s?", "", line).strip() for line in block.splitlines()]
        comments.append(" ".join(line for line in lines if line))
    return [c for c in comments if c]


def heuristic_score(text, suffix):
    text = BANNER_42.sub("", text)
    comments = extract_comments(text, suffix)
    comment_text = "\n".join(comments)
    code_lines = [line for line in text.splitlines() if line.strip()]
    points = 0.0
    reasons = []

    mention = AI_MENTIONS.search(text)
    if mention:
        points += 4
        reasons.append(f"mentionne une IA ({mention.group(0)})")

    symbols = LLM_SYMBOLS.findall(text)
    if symbols:
        points += min(3, 1.5 + 0.3 * len(symbols))
        reasons.append(f"{len(symbols)} symbole(s) typique(s) d'IA ({''.join(sorted(set(symbols))[:5])})")

    if CODE_FENCE.search(text):
        points += 3
        reasons.append("bloc ``` markdown oublie dans le code")

    found = sorted({match.group(0).lower() for match in LLM_PHRASES.finditer(comment_text)})
    if found:
        points += min(2.5, 0.7 * len(found))
        reasons.append(f"tournures d'IA dans les commentaires ({', '.join(found[:4])})")

    doc_tags = len(DOC_TAGS.findall(comment_text)) + len(DOCSTRING_SECTIONS.findall(text))
    if doc_tags >= 2:
        points += min(1.0, 0.25 * doc_tags)
        reasons.append(f"{doc_tags} balise(s) de doc (@brief/@param/Args:)")

    comment_lines = sum(c.count("\n") + 1 for c in comments)
    ratio = comment_lines / max(1, len(code_lines))
    if len(comments) >= 3 and ratio > 0.12:
        points += 0.6 if ratio < 0.25 else 1.0
        reasons.append(f"densite de commentaires elevee ({ratio:.0%})")

    if len(comments) >= 3:
        step_ratio = sum(1 for c in comments if STEP_VERBS.match(c)) / len(comments)
        if step_ratio >= 0.4:
            points += 1.2
            reasons.append(f"commentaires 'etape par etape' ({step_ratio:.0%})")

    trailing = re.findall(r"[;{)]\s+//\s*[A-Z]", text)
    if len(trailing) >= 3:
        points += 0.5
        reasons.append(f"{len(trailing)} commentaires en fin de ligne")

    if SECTION_BANNER.search(text):
        points += 0.5
        reasons.append("bannieres de section (// ====)")

    errors = ERROR_PREFIX.findall(text)
    if len(errors) >= 2:
        points += 0.6
        reasons.append(f"messages 'Error: ...' ({len(errors)})")

    return 1 - math.exp(-points / 2), reasons


class Binoculars:
    def __init__(self, threads):
        os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
        os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
        import torch
        import transformers

        transformers.logging.set_verbosity_error()
        transformers.logging.disable_progress_bar()
        torch.set_num_threads(threads)
        self.torch = torch
        base = "Qwen/Qwen2.5-Coder-0.5B"
        self.tokenizer = transformers.AutoTokenizer.from_pretrained(base)
        load = transformers.AutoModelForCausalLM.from_pretrained
        self.observer = load(base, dtype=torch.float32).eval()
        self.performer = load(base + "-Instruct", dtype=torch.float32).eval()

    def score(self, text, max_tokens=768, max_chunks=3):
        text = BANNER_42.sub("", text)
        ids = self.tokenizer(text, return_tensors="pt").input_ids[0]
        if len(ids) < 40:
            return None, len(ids)
        chunks = [ids[i:i + max_tokens] for i in range(0, len(ids), max_tokens)]
        chunks = [c for c in chunks if len(c) >= 40][:max_chunks]
        total_ppl = 0.0
        total_xppl = 0.0
        total_tokens = 0
        functional = self.torch.nn.functional
        with self.torch.no_grad():
            for chunk in chunks:
                batch = chunk.unsqueeze(0)
                observer_logits = self.observer(batch).logits[0, :-1]
                performer_logits = self.performer(batch).logits[0, :-1]
                targets = chunk[1:]
                ppl = functional.cross_entropy(performer_logits, targets, reduction="sum")
                xppl = (functional.softmax(observer_logits, -1)
                        * -functional.log_softmax(performer_logits, -1)).sum()
                total_ppl += ppl.item()
                total_xppl += xppl.item()
                total_tokens += len(targets)
        return total_ppl / total_xppl, total_tokens


def model_probability(binoculars_score, tokens, threshold):
    raw = 1 / (1 + math.exp((binoculars_score - threshold) / 0.05))
    return raw * min(1.0, tokens / 250)


def git_evidence(root):
    try:
        top = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        log = subprocess.run(
            ["git", "-C", top, "log", "--all", "--format=%H%x00%an%x00%B%x01"],
            capture_output=True, text=True, check=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    evidence = []
    for entry in log.split("\x01"):
        parts = entry.strip().split("\x00")
        if len(parts) < 3:
            continue
        match = AI_COMMIT_PATTERNS.search(parts[2])
        if match:
            evidence.append(f"commit {parts[0][:8]} : '{match.group(0).strip()}'")
    return evidence


def repo_evidence(root):
    evidence = []
    for name in AI_TOOL_FILES:
        for found in [root / name, *root.glob(f"**/{name}")]:
            if found.exists() and not any(p in IGNORED_DIRS for p in found.parts):
                evidence.append(f"fichier d'outil IA : {found.relative_to(root) if found != root else name}")
                break
    for readme in root.glob("**/README*"):
        if any(p in IGNORED_DIRS for p in readme.parts):
            continue
        content = readme.read_text(errors="ignore")
        emoji_titles = re.findall(r"^#+ .*[\U0001f300-\U0001faff✅✨⚡]", content, re.M)
        if len(emoji_titles) >= 2:
            evidence.append(f"{readme.relative_to(root)} : titres avec emojis ({len(emoji_titles)})")
    return sorted(set(evidence)) + git_evidence(root)


def verdict(probability):
    if probability >= 0.7:
        return color("IA probable", "1;31")
    if probability >= 0.45:
        return color("suspect", "1;33")
    return color("humain probable", "1;32")


def main():
    parser = argparse.ArgumentParser(description="Detecte si du code a ete ecrit par une IA.")
    parser.add_argument("folder", type=Path)
    parser.add_argument("--fast", action="store_true", help="heuristiques seulement, sans modele")
    parser.add_argument("-v", "--verbose", action="store_true", help="affiche les raisons pour chaque fichier")
    parser.add_argument("--threshold", type=float, default=0.70, help="seuil Binoculars (plus bas = plus IA)")
    parser.add_argument("--threads", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    args = parser.parse_args()

    root = args.folder.resolve()
    if not root.is_dir():
        sys.exit(f"{args.folder} n'est pas un dossier")

    files = collect_files(root)
    if not files:
        sys.exit("aucun fichier source trouve")

    detector = None
    if not args.fast:
        print(color("chargement des modeles...", "2"), file=sys.stderr)
        detector = Binoculars(args.threads)

    results = []
    for index, (path, text) in enumerate(files, 1):
        relative = path.relative_to(root)
        if sys.stderr.isatty():
            print(f"\033[2m[{index}/{len(files)}] {relative}\033[0m\033[K", end="\r", file=sys.stderr)
        heuristic, reasons = heuristic_score(text, path.suffix)
        binoculars, tokens = (None, len(text) // 4)
        if detector:
            binoculars, tokens = detector.score(text)
        if binoculars is None:
            probability = heuristic
        else:
            model = model_probability(binoculars, tokens, args.threshold)
            probability = 1 - (1 - model) * (1 - 0.6 * heuristic)
        results.append((relative, probability, binoculars, heuristic, reasons, tokens))
    if sys.stderr.isatty():
        print("\033[K", end="", file=sys.stderr)

    prefix = Path(os.path.commonpath([r[0].parent for r in results])) if len(results) > 1 else Path()
    results = [(r[0].relative_to(prefix), *r[1:]) for r in results]
    width = min(60, max(len(str(r[0])) for r in results))
    header = f"{'fichier':<{width}}  {'IA':>5}  {'binoc':>6}  {'heur':>5}  verdict"
    print(color(header, "1"))
    for relative, probability, binoculars, heuristic, reasons, _ in sorted(results, key=lambda r: -r[1]):
        name = str(relative)
        if len(name) > width:
            name = "..." + name[-width + 3:]
        binoc_text = f"{binoculars:6.3f}" if binoculars is not None else "     -"
        print(f"{name:<{width}}  {probability:5.0%}  {binoc_text}  {heuristic:5.0%}  {verdict(probability)}")
        if args.verbose:
            for reason in reasons:
                print(color(f"    - {reason}", "2"))

    total_weight = sum(max(r[5], 1) for r in results)
    overall = sum(r[1] * max(r[5], 1) for r in results) / total_weight
    flagged = sum(1 for r in results if r[1] >= 0.7)
    evidence = repo_evidence(root)

    print()
    if evidence:
        print(color("Preuves directes :", "1;31"))
        for item in evidence[:15]:
            print(f"  - {item}")
        if len(evidence) > 15:
            print(f"  ... et {len(evidence) - 15} autres")
        if any(item.startswith(("fichier", "commit")) for item in evidence):
            overall = max(overall, 0.9)
    print(color("Resultat global : ", "1") + f"{overall:.0%}  {verdict(overall)}"
          + f"  ({flagged}/{len(results)} fichiers marques IA)")
    print(color("Ce n'est qu'une estimation statistique : aucun detecteur n'est fiable a 100%.", "2"))


if __name__ == "__main__":
    main()
